async (page) => {
  const packet=__DEMO_PACKET__;
  const out='F:/projects/NLPClass/outputs/exp1/final_report_assets/20260927_010652/screenshots/';
  const errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.route('**/static/**',route=>route.continue());
  await page.route('**/api/v1/analyze',route=>route.fulfill({json:packet.analysis}));
  await page.route('**/api/v1/experiments/1/trace?*',route=>route.fulfill({json:packet.trace}));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8000/');
  const home=await page.locator('main').innerText();
  await page.screenshot({path:out+'01-experiment-overview.png',fullPage:true});
  await page.goto('http://127.0.0.1:8000/sequence');
  await page.waitForFunction(()=>document.querySelector('#run-select').options.length>1);
  await page.locator('#task-ner').uncheck();
  await page.locator('#input-text').fill(packet.analysis.text);
  await page.locator('#analyze-button').click();
  await page.waitForFunction(()=>!document.querySelector('#analyze-button').disabled && document.querySelector('#model-details').innerText.includes('Transition A'));
  const labels=await page.locator('.page-header').innerText();
  const sources=await page.locator('.benchmark-sources').innerText();
  await page.locator('#report-toggle').click();
  await page.screenshot({path:out+'13-interactive-segmentation.png',fullPage:true});
  await page.locator('#tab-parameters').click();
  await page.waitForFunction(()=>document.querySelector('#model-specific-parameters').innerText.includes('Transition A'));
  await page.screenshot({path:out+'02-hmm-pi-a-b.png',fullPage:true});
  await page.locator('#tab-metrics').click();
  await page.waitForFunction(()=>document.querySelector('#comparison-table').innerText.includes('94.73% *'));
  const table=await page.locator('#comparison-table').innerText();
  await page.locator('#comparison-table').screenshot({path:out+'10-seven-model-comparison.png'});
  await page.locator('#tab-errors').click();
  await page.waitForFunction(()=>document.querySelector('#error-list').innerText.length>100);
  await page.screenshot({path:out+'12-error-analysis.png',fullPage:true});
  await page.locator('#tab-interactive').click();
  await page.locator('#report-toggle').click();
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);
  await page.screenshot({path:out+'mobile-source-labels.png',fullPage:true});
  const narrow=await page.evaluate(()=>({width:innerWidth,scroll_width:document.documentElement.scrollWidth}));
  await page.unroute('**/api/v1/analyze');
  await page.unroute('**/api/v1/experiments/1/trace?*');
  return {home,labels,sources,table,narrow,errors,replayed_saved_demo:true,inference_executed:false,training_executed:false,official_test_inference_executed:false,scorer_executed:false};
}
